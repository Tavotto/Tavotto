def _convert_output_ok(root: str, target_rel: str, output: str, resume_sha256: str = "") -> bool:
    """顶层的精确候选名；新建必须不存在，续跑必须匹配父进程授权的普通文件字节。"""
    if not output or "\x00" in output or output != os.path.basename(output) or "\\" in output:
        return False
    stem = Path(target_rel).stem
    if not stem or output != stem + CONVERT_SUFFIX:
        return False
    path = os.path.join(root, output)
    if not resume_sha256:
        return not os.path.lexists(path)
    if not re.fullmatch(r"[0-9a-f]{64}", resume_sha256):
        return False
    try:
        before = os.stat(path, follow_symlinks=False)
        if not stat.S_ISREG(before.st_mode) or before.st_size > READ_LIMIT_BYTES:
            return False
        flags = (
            os.O_RDONLY
            | getattr(os, "O_NOFOLLOW", 0)
            | getattr(os, "O_NONBLOCK", 0)
            | getattr(os, "O_BINARY", 0)
        )
        with os.fdopen(os.open(path, flags), "rb") as stream:
            opened = os.fstat(stream.fileno())
            if not stat.S_ISREG(opened.st_mode) or _file_identity(
                before, change_time=False
            ) != _file_identity(opened, change_time=False):
                return False
            raw = stream.read(READ_LIMIT_BYTES + 1)
            after = os.fstat(stream.fileno())
        latest = os.stat(path, follow_symlinks=False)
        return (
            _file_identity(before, change_time=False) == _file_identity(opened, change_time=False)
            and _file_identity(opened) == _file_identity(after)
            and _file_identity(before) == _file_identity(latest)
            and len(raw) <= READ_LIMIT_BYTES
            and _sha(raw) == resume_sha256
        )
    except OSError:
        return False


class ConvertSession(FigureEditSession):
    """convert_to_editable 的一次运行：原脚本只读，唯一可写的是 `--output` 那个新文件。路径判据复用 `_resolve`。"""

    def __init__(self, envelope: RunEnvelope):
        super().__init__(envelope)
        if not self.target_usable():  # 原脚本必须能读（同 figure_edit），否则不发任何模型请求
            raise BadEnvelope("bad_target")
        if not _convert_output_ok(
            self.root, envelope.target, envelope.output, envelope.resume_output_sha256
        ):
            raise BadEnvelope("bad_output")
        self.output_rel = envelope.output
        self.output_path = self._resolve(envelope.output)
        if self.output_path is None or os.path.dirname(self.output_path) != self.root:
            raise BadEnvelope("bad_output")
        self.created = bool(envelope.resume_output_sha256)
        if (
            type(envelope.checks_used) is not int
            or not 0 <= envelope.checks_used <= CONVERT_MAX_CHECKS
        ):
            raise BadEnvelope("bad_output")
        self.checks_run = envelope.checks_used

    def list_dir(self, args: dict, call_id: str = "") -> ToolResult:
        directory = self._resolve(args.get("path", "."))
        if directory is None:
            return _err(
                "list_dir", call_id, "path_outside", "Path is not inside the candidate directory."
            )
        return self._list_dir(directory, call_id)

    def _is_output(self, real: str) -> bool:
        return os.path.normcase(real) == os.path.normcase(self.output_path or "")

    def _writable_output(self, name: str, call_id: str, path: object) -> str | ToolResult:
        real = self._resolve(path)
        if real is None:
            return _err(name, call_id, "path_outside", "Path is not inside the project directory.")
        if self._is_target(real):
            return _err(
                name,
                call_id,
                "source_readonly",
                f"The original script ({self.target_rel}) is read-only and must not be changed.",
            )
        if not self._is_output(real):
            return _err(
                name,
                call_id,
                "not_output",
                f"Only the new file ({self.output_rel}) may be written.",
            )
        return real

    def create_file(self, args: dict, call_id: str = "") -> ToolResult:
        name = "create_file"
        content = args.get("content")
        if not isinstance(content, str):
            return _err(name, call_id, "bad_arguments", "`content` must be a string.")
        real = self._writable_output(name, call_id, args.get("path", self.output_rel))
        if isinstance(real, ToolResult):
            return real
        if not content.strip():
            return _err(name, call_id, "empty_content", "`content` must not be empty.")
        if len(content.encode("utf-8")) > READ_LIMIT_BYTES:
            return _err(name, call_id, "too_large", "Content is larger than the allowed size.")
        text = content.replace("\r\n", "\n")
        if not self.created:
            # 新建前没有「写入前的文本」：整份内容含密钥就拒，且必须在建文件之前（零改动）
            if self.redactor.contains(text):
                return _secret_err(name, call_id)
            # 第一次：新建。O_EXCL —— 此刻已存在（含悬空符号链接）就失败，绝不覆盖别人的文件
            try:
                fd = os.open(real, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o644)
            except FileExistsError:
                return _err(name, call_id, "output_exists", "The output file already exists.")
            with os.fdopen(fd, "wb") as f:
                f.write(text.encode("utf-8"))
                f.flush()
                os.fsync(f.fileno())
            self.created = True
            verb = "created"
        else:
            got = self._read_text(real)
            before = got[0] if not isinstance(got, str) else ""
            refused = self._commit_write(name, call_id, real, before, text, "\n")
            if refused is not None:
                return refused
            verb = "rewrote"
        n = text.count("\n") + (0 if text.endswith("\n") else 1)
        return ToolResult(
            call_id,
            name,
            f"Wrote {self.output_rel}. sha256: {_sha(text.encode('utf-8'))}",
            summary=f"{verb} {n} lines",
            mutated=True,
        )

    def append_file(self, args: dict, call_id: str = "") -> ToolResult:
        name = "append_file"
        real = self._writable_output(name, call_id, args.get("path", self.output_rel))
        if isinstance(real, ToolResult):
            return real
        if not self.created:
            return _err(
                name, call_id, "not_created", "Create the first section with create_file first."
            )
        content, expected = args.get("content"), args.get("expected_sha256")
        if not isinstance(content, str) or not content or not isinstance(expected, str):
            return _err(
                name,
                call_id,
                "bad_arguments",
                "Supply content and the sha256 returned by the previous write.",
            )
        got = self._read_text(real)
        if isinstance(got, str):
            return _err(name, call_id, got, "The new file can no longer be read as text.")
        before, eol = got
        if _sha(before.encode("utf-8")) != expected:
            return _err(
                name,
                call_id,
                "file_changed",
                "File differs from the expected sha256; read it and use edit_file to continue. Nothing appended.",
            )
        after = before + content.replace("\r\n", "\n")
        refused = self._commit_write(name, call_id, real, before, after, eol)
        if refused is not None:
            return refused
        return ToolResult(
            call_id,
            name,
            f"Appended to {self.output_rel}. sha256: {_sha(after.encode('utf-8'))}",
            summary="appended code",
            mutated=True,
        )

    def edit_file(self, args: dict, call_id: str = "") -> ToolResult:
        name = "edit_file"
        try:
            old, new = _edit_text_arguments(args)
        except ValueError as exc:
            return _err(name, call_id, "bad_arguments", str(exc))
        real = self._writable_output(name, call_id, args.get("path", self.output_rel))
        if isinstance(real, ToolResult):
            return real
        if not self.created:
            return _err(
                name,
                call_id,
                "not_created",
                "Create the new file with create_file before editing it.",
            )
        if old == "":
            return _err(name, call_id, "empty_old", "`old` must not be empty.")
        if old == new:
            return _err(name, call_id, "no_change", "`old` and `new` are identical; nothing to do.")
        got = self._read_text(real)
        if isinstance(got, str):
            return _err(name, call_id, got, "The new file can no longer be read as text.")
        text, eol = got
        old_n, new_n = old.replace("\r\n", "\n"), new.replace("\r\n", "\n")
        count = text.count(old_n)
        if count == 0:
            return _err(
                name,
                call_id,
                "old_not_found",
                "`old` was not found in the file. It must match exactly, including whitespace and "
                "indentation. Read the file again and copy the text verbatim.",
            )
        if count > 1:
            return _err(
                name,
                call_id,
                "old_not_unique",
                f"`old` appears {count} times in the file. Include more surrounding lines so that "
                "it matches exactly once.",
            )
        updated = text.replace(old_n, new_n, 1)
        refused = self._commit_write(name, call_id, real, text, updated, eol)
        if refused is not None:
            return refused
        return ToolResult(
            call_id,
            name,
            f"Edited {self.output_rel}. sha256: {_sha(updated.encode('utf-8'))}",
            summary="edited new file",
            mutated=True,
        )

    def check(self, args: dict, call_id: str = "") -> ToolResult:
        name = "check"
        final = args.get("final", False)
        summary = args.get("summary", "")
        if type(final) is not bool or not isinstance(summary, str):
            return _err(
                name, call_id, "bad_arguments", "`final` must be boolean and `summary` a string."
            )
        # 先报可操作的流程错误（还没建文件），再报环境限制（本会话没有 check）
        if not self.created:
            return _err(name, call_id, "not_created", "Create the new file with create_file first.")
        if self.check_fn is None:
            return _err(name, call_id, "not_available", "check is not available in this session.")
        result = super().check(args, call_id)
        if final and result.check_passed is True and not result.is_error:
            result.completed = True
            result.completion_text = summary.strip() or result.content
        return result

    def finish(self, args: dict, call_id: str = "") -> ToolResult:
        # One validation authority and one shared check budget. Calling this
        # explicitly declares delivery intent; a diagnostic check never does.
        return self.check({"final": True, "summary": args.get("summary", "")}, call_id)


