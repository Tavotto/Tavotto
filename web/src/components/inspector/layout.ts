/**
 * 检查器的行版式常量。
 *
 * **标签列宽只有一个数**（2026-09-15 全面打磨 L1）。此前同一个面板里有四种：
 * `Row` 的默认 44、排列网格的 3.75rem（60）、画布页与文字段的 72、图内元素页的 88
 * ——画布对象页一页就占了两种（缩放 / 取景那几行控件从 x65 起，对齐 / 层级从 x81 起），
 * 读不出一条控件竖线。一个表单一种行语法：所有检查器的行都显式传这个常量。
 *
 * 为什么是 88 而不是更窄：72 时 en-US 在出厂宽度 360 会把「Stacking order /
 * Frame opacity / Major tick mode / Number format」截成省略号，要悬停才知道是什么
 * （2026-09-12 critique P2）。88 容得下这四个。
 *
 * 常量放在 `inspector/` 而不是 `ui/Field.tsx`：`Row` 是通用原语（左栏的素材筛选行
 * 用 36、设置页另有自己的一档），它的默认值不该被检查器的口径绑架——调用点显式传。
 */
export const INSPECTOR_LABEL_W = 88

/** 同宽的 Tailwind 类名，给不走 `Row`（自己排网格 / 开关行）的地方用 */
export const INSPECTOR_LABEL_COL = 'w-22'
